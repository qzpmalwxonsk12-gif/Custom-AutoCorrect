package com.arjun.autocorrect.engine

import kotlin.math.hypot
import kotlin.math.max
import kotlin.math.min

/**
 * Explicit QWERTY letter-key neighbourhoods used by Process 3.
 *
 * Candidate generation must be inspectable and deterministic, so this map is
 * the source of truth. The coordinate model below is retained only for ranking
 * candidates the map has already admitted - geometry never decides which
 * substitutions may be generated.
 */
val KEY_NEIGHBOURS: Map<Char, List<Char>> = mapOf(
    'q' to listOf('w', 'a'),
    'w' to listOf('q', 'e', 'a', 's', 'd'),
    'e' to listOf('w', 'r', 's', 'd', 'f'),
    'r' to listOf('e', 't', 'd', 'f', 'g'),
    't' to listOf('r', 'y', 'f', 'g', 'h'),
    'y' to listOf('t', 'u', 'g', 'h', 'j'),
    'u' to listOf('y', 'i', 'h', 'j', 'k'),
    'i' to listOf('u', 'o', 'j', 'k', 'l'),
    'o' to listOf('i', 'p', 'j', 'k', 'l'),
    'p' to listOf('o', 'l'),

    'a' to listOf('q', 'w', 's', 'z', 'x'),
    's' to listOf('q', 'w', 'e', 'a', 'd', 'z', 'x', 'c'),
    'd' to listOf('w', 'e', 'r', 's', 'f', 'x', 'c', 'v'),
    'f' to listOf('e', 'r', 't', 'd', 'g', 'c', 'v', 'b'),
    'g' to listOf('r', 't', 'y', 'f', 'h', 'v', 'b', 'n'),
    'h' to listOf('t', 'y', 'u', 'g', 'j', 'b', 'n', 'm'),
    'j' to listOf('y', 'u', 'i', 'o', 'h', 'k', 'n'),
    'k' to listOf('u', 'i', 'o', 'j', 'l', 'm'),
    'l' to listOf('i', 'o', 'p', 'k', 'm'),

    'z' to listOf('a', 'x'),
    'x' to listOf('z', 'c', 'a', 's', 'd'),
    'c' to listOf('x', 'v', 's', 'd', 'f'),
    'v' to listOf('c', 'b', 'd', 'f', 'g'),
    'b' to listOf('v', 'n', 'f', 'g', 'h'),
    'n' to listOf('b', 'm', 'g', 'h', 'j'),
    'm' to listOf('l', 'n'),
)

/**
 * The deliberate two-neighbour corner rule makes these pairs directional.
 * Every other relationship in [KEY_NEIGHBOURS] is symmetrical, and a unit test
 * holds that invariant in place.
 */
val KEY_NEIGHBOUR_SYMMETRY_EXCEPTIONS: List<Pair<Char, Char>> = listOf(
    // [corner, surrounding key]: the corner omits the reverse relationship.
    'q' to 's',
    'z' to 's',
    'm' to 'h',
    'm' to 'k',
)

/** QWERTY coordinates used only to score map-approved substitutions. */
private val ROWS = listOf("qwertyuiop", "asdfghjkl", "zxcvbnm")
private val ROW_OFFSET = doubleArrayOf(0.0, 0.25, 0.75)

private val COORDS: Map<Char, Pair<Double, Double>> = buildMap {
    for (rowIndex in ROWS.indices) {
        val row = ROWS[rowIndex]
        for (column in row.indices) {
            put(row[column], (column + ROW_OFFSET[rowIndex]) to rowIndex.toDouble())
        }
    }
}

/** Euclidean distance in key widths; [Double.POSITIVE_INFINITY] when unknown. */
fun keyDistance(a: Char, b: Char): Double {
    val source = a.lowercaseChar()
    val target = b.lowercaseChar()
    if (source == target) return 0.0
    val sp = COORDS[source] ?: return Double.POSITIVE_INFINITY
    val tp = COORDS[target] ?: return Double.POSITIVE_INFINITY
    return hypot(sp.first - tp.first, sp.second - tp.second)
}

/** Map membership, not geometric distance, defines adjacency. */
fun areAdjacent(a: Char, b: Char): Boolean {
    val source = a.lowercaseChar()
    val target = b.lowercaseChar()
    if (source == target) return false
    return KEY_NEIGHBOURS[source]?.contains(target) ?: false
}

/**
 * 0..1 plausibility that [typed] was a slip for [intended], from key distance
 * alone. This ranks candidates already generated by [KEY_NEIGHBOURS]; it never
 * decides whether a candidate may be generated.
 */
fun proximityScore(typed: String, intended: String): Double {
    val source = typed.lowercase()
    val target = intended.lowercase()
    if (source.length != target.length) return 0.0

    var worstDistance = 0.0
    var differences = 0
    for (index in source.indices) {
        if (source[index] == target[index]) continue
        differences++
        val distance = keyDistance(source[index], target[index])
        if (!distance.isFinite()) return 0.0
        worstDistance = max(worstDistance, distance)
    }

    if (differences == 0) return 1.0
    if (differences > 2) return 0.0

    val perKeyScore = max(0.0, 1 - (worstDistance - 1) / 3)
    val score = if (differences == 1) perKeyScore else perKeyScore * 0.6
    return max(0.0, min(1.0, score))
}

/** Neighbours of [ch], or an empty list for a non-letter. */
fun neighbours(ch: Char): List<Char> = KEY_NEIGHBOURS[ch.lowercaseChar()] ?: emptyList()
