/**
 * Explicit QWERTY letter-key neighbourhoods used by Process 3.
 *
 * Candidate generation must be inspectable and deterministic, so this map is
 * the source of truth. The coordinate model below is retained only for ranking
 * candidates that the map has already admitted.
 */
export const KEY_NEIGHBOURS = {
  q: ['w', 'a'],
  w: ['q', 'e', 'a', 's', 'd'],
  e: ['w', 'r', 's', 'd', 'f'],
  r: ['e', 't', 'd', 'f', 'g'],
  t: ['r', 'y', 'f', 'g', 'h'],
  y: ['t', 'u', 'g', 'h', 'j'],
  u: ['y', 'i', 'h', 'j', 'k'],
  i: ['u', 'o', 'j', 'k', 'l'],
  o: ['i', 'p', 'j', 'k', 'l'],
  p: ['o', 'l'],

  a: ['q', 'w', 's', 'z', 'x'],
  s: ['q', 'w', 'e', 'a', 'd', 'z', 'x', 'c'],
  d: ['w', 'e', 'r', 's', 'f', 'x', 'c', 'v'],
  f: ['e', 'r', 't', 'd', 'g', 'c', 'v', 'b'],
  g: ['r', 't', 'y', 'f', 'h', 'v', 'b', 'n'],
  h: ['t', 'y', 'u', 'g', 'j', 'b', 'n', 'm'],
  j: ['y', 'u', 'i', 'o', 'h', 'k', 'n'],
  k: ['u', 'i', 'o', 'j', 'l', 'm'],
  l: ['i', 'o', 'p', 'k', 'm'],

  z: ['a', 'x'],
  x: ['z', 'c', 'a', 's', 'd'],
  c: ['x', 'v', 's', 'd', 'f'],
  v: ['c', 'b', 'd', 'f', 'g'],
  b: ['v', 'n', 'f', 'g', 'h'],
  n: ['b', 'm', 'g', 'h', 'j'],
  m: ['l', 'n'],
} as const satisfies Readonly<Record<string, readonly string[]>>;

for (const values of Object.values(KEY_NEIGHBOURS)) Object.freeze(values);
Object.freeze(KEY_NEIGHBOURS);

/**
 * The deliberate two-neighbour corner rule makes these pairs directional.
 * Every other relationship in KEY_NEIGHBOURS is symmetrical.
 */
export const KEY_NEIGHBOUR_SYMMETRY_EXCEPTIONS = [
  // [corner, surrounding key]: the corner omits the reverse relationship.
  ['q', 's'],
  ['z', 's'],
  ['m', 'h'],
  ['m', 'k'],
] as const satisfies readonly (readonly [string, string])[];

const KEY_NEIGHBOUR_LOOKUP: Readonly<
  Record<string, readonly string[] | undefined>
> = KEY_NEIGHBOURS;

/** QWERTY coordinates used only to score map-approved substitutions. */
const ROWS = ['qwertyuiop', 'asdfghjkl', 'zxcvbnm'];
const ROW_OFFSET = [0, 0.25, 0.75];

const COORDS = new Map<string, { x: number; y: number }>();
for (let rowIndex = 0; rowIndex < ROWS.length; rowIndex++) {
  const row = ROWS[rowIndex]!;
  for (let column = 0; column < row.length; column++) {
    COORDS.set(row[column]!, {
      x: column + ROW_OFFSET[rowIndex]!,
      y: rowIndex,
    });
  }
}

/** Euclidean distance in key widths; `Infinity` for unknown characters. */
export function keyDistance(a: string, b: string): number {
  const source = a.toLowerCase();
  const target = b.toLowerCase();
  if (source === target) return 0;
  const sourcePosition = COORDS.get(source);
  const targetPosition = COORDS.get(target);
  if (!sourcePosition || !targetPosition) return Infinity;
  return Math.hypot(
    sourcePosition.x - targetPosition.x,
    sourcePosition.y - targetPosition.y,
  );
}

/** Map membership, not geometric distance, defines adjacency. */
export function areAdjacent(a: string, b: string): boolean {
  const source = a.toLowerCase();
  const target = b.toLowerCase();
  if (source === target) return false;
  return KEY_NEIGHBOUR_LOOKUP[source]?.includes(target) ?? false;
}

/**
 * 0..1 plausibility that `typed` was a slip for `intended`, based only on key
 * distance. This ranks candidates already generated by KEY_NEIGHBOURS; it
 * never decides whether a candidate may be generated.
 */
export function proximityScore(typed: string, intended: string): number {
  const source = typed.toLowerCase();
  const target = intended.toLowerCase();
  if (source.length !== target.length) return 0;

  let worstDistance = 0;
  let differences = 0;
  for (let index = 0; index < source.length; index++) {
    if (source[index] === target[index]) continue;
    differences++;
    const distance = keyDistance(source[index]!, target[index]!);
    if (!Number.isFinite(distance)) return 0;
    worstDistance = Math.max(worstDistance, distance);
  }

  if (differences === 0) return 1;
  if (differences > 2) return 0;

  const perKeyScore = Math.max(0, 1 - (worstDistance - 1) / 3);
  const score = differences === 1 ? perKeyScore : perKeyScore * 0.6;
  return Math.max(0, Math.min(1, score));
}

/** Returns a copy so callers cannot mutate the source-of-truth map. */
export function neighbours(ch: string): string[] {
  const normalised = ch.toLowerCase();
  return [...(KEY_NEIGHBOUR_LOOKUP[normalised] ?? [])];
}
